import AppKit

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published var isPaused = false

    static let ignoredAppsKey = "ignoredBundleIDs"

    private let store: HistoryStore
    private let defaults: UserDefaults
    private let frontmostBundleID: () -> String?
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int?

    /// Types password managers (and other privacy-aware apps) attach to payloads
    /// that must never be recorded. See http://nspasteboard.org
    static let privacyMarkerTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init(
        store: HistoryStore,
        defaults: UserDefaults = .standard,
        frontmostBundleID: @escaping () -> String? = {
            NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        }
    ) {
        self.store = store
        self.defaults = defaults
        self.frontmostBundleID = frontmostBundleID
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Writes an item back to the clipboard, marking the resulting change so the
    /// next poll doesn't re-record it as a duplicate.
    func copyBack(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        ignoredChangeCount = pasteboard.changeCount
    }

    func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == ignoredChangeCount {
            ignoredChangeCount = nil
            return
        }
        guard !isPaused else { return }
        guard !Self.isPrivacyMarked(pasteboard) else { return }
        guard !isFrontmostAppIgnored() else { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        store.add(text)
    }

    /// The pasteboard doesn't record which app wrote to it, so the app in front
    /// at poll time stands in for the source. Known limitation: a copy made just
    /// before switching apps (within one 0.5s poll) is attributed to the new app.
    private func isFrontmostAppIgnored() -> Bool {
        guard let bundleID = frontmostBundleID() else { return false }
        let ignored = defaults.stringArray(forKey: Self.ignoredAppsKey) ?? []
        return ignored.contains(bundleID)
    }

    static func isPrivacyMarked(_ pasteboard: NSPasteboard) -> Bool {
        guard let types = pasteboard.types else { return false }
        return privacyMarkerTypes.contains(where: types.contains)
    }
}
